export const VERSION = '0.1.0';

const describe = (hex) => ({
  hex,
  rgb: hexToRgb(hex),
  hsl: hexToHsl(hex),
  oklch: hexToOklch(hex),
});

// Dark-flavor ANSI mapping from the Catppuccin style guide. Black and white use
// neutrals for both normal and bright. The 6 hues derive bright from normal.
const ANSI = [
  ['black', 'Black', 'surface1', 'surface2'],
  ['red', 'Red', 'red'],
  ['green', 'Green', 'green'],
  ['yellow', 'Yellow', 'yellow'],
  ['blue', 'Blue', 'blue'],
  ['magenta', 'Magenta', 'pink'],
  ['cyan', 'Cyan', 'teal'],
  ['white', 'White', 'subtext0', 'subtext1'],
];

export const buildPalette = () => {
  const flavorColors = Object.fromEntries(
    Object.entries(colors).map(([key, c]) => {
      const { hex, rgb, hsl, oklch } = describe(c.hex);
      return [key, { name: c.name, order: c.order, hex, rgb, hsl, oklch, accent: c.accent }];
    }),
  );

  const ansiColors = Object.fromEntries(
    ANSI.map(([key, name, normalRole, brightRole], order) => {
      const normalHex = colors[normalRole].hex;
      const brightHex = brightRole ? colors[brightRole].hex : brightVariant(normalHex);
      return [
        key,
        {
          name,
          order,
          normal: { name, ...describe(normalHex), code: order },
          bright: { name: `Bright ${name}`, ...describe(brightHex), code: order + 8 },
        },
      ];
    }),
  );

  return {
    version: VERSION,
    [flavor.key]: {
      name: flavor.name,
      emoji: flavor.emoji,
      order: flavor.order,
      dark: flavor.dark,
      colors: flavorColors,
      ansiColors,
    },
  };
};

const entries = (palette) => Object.entries(palette[flavor.key].colors);

export const buildCss = (palette) => {
  const lines = entries(palette).flatMap(([key, c]) => [
    `  --ctp-${key}: ${c.hex};`,
    `  --ctp-${key}-rgb: ${c.rgb.r} ${c.rgb.g} ${c.rgb.b};`,
  ]);
  return `/* Cyber Cat ${palette.version}. Generated by src/build.mjs. Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`;
};

export const buildScss = (palette) => {
  const vars = entries(palette).map(([key, c]) => `$${key}: ${c.hex};`);
  const map = entries(palette).map(([key]) => `  "${key}": $${key},`);
  return `// Cyber Cat ${palette.version}. Generated by src/build.mjs. Do not edit.\n// Use with: @use "cyber-cat" as ctp;\n\n${vars.join('\n')}\n\n$colors: (\n${map.join('\n')}\n);\n`;
};

const esc = (s) => s.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');

